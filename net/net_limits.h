#ifndef NET_LIMITS_H
#define NET_LIMITS_H

#define NET_ETHERNET_MTU 1500U
#define NET_ETHERNET_HEADER_SIZE 14U
#define NET_ETHERNET_MIN_FRAME_SIZE 60U
#define NET_IPV4_HEADER_SIZE 20U
#define NET_UDP_HEADER_SIZE 8U
#define NET_ETHERNET_FRAME_MAX_SIZE (NET_ETHERNET_HEADER_SIZE + NET_ETHERNET_MTU)
#define NET_ETHERNET_FCS_SIZE 4U
#define NET_ETHERNET_FRAME_WITH_FCS_MAX_SIZE \
    (NET_ETHERNET_FRAME_MAX_SIZE + NET_ETHERNET_FCS_SIZE)
#define NET_UDP_PAYLOAD_MAX_SIZE \
    (NET_ETHERNET_MTU - NET_IPV4_HEADER_SIZE - NET_UDP_HEADER_SIZE)

#endif
